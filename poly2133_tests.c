#define NUM_LIMBS 8
#define TAG_SIZE 27
#define KEY_SIZE 54

int run_test(const char* test_name, const unsigned char key[KEY_SIZE], const unsigned char* data, uint64_t data_len, const unsigned char true_tag[TAG_SIZE]){
    uint32_t acc[NUM_LIMBS], r[NUM_LIMBS], s[NUM_LIMBS];
    int test_passed;
    unsigned char* tag;

    poly1305_init(acc, r, s, key); // create acc, r and s from key
    tag = create_tag(acc, r, s, data, data_len); // create the tag

    test_passed = (memcmp(tag, true_tag, TAG_SIZE) == 0); // test whether generated tag is equal to true tag

    if(test_passed){
        printf("%s [PASSED]\n", test_name);
    } else{
        printf("%s [FAILED]\n", test_name);
        printf("Expected tag: ");
        for(uint64_t i = 0; i < TAG_SIZE; i++){
            printf("%02x ", true_tag[i]);
        }
        printf("\nGenerated tag: ");
        for(uint64_t i = 0; i < TAG_SIZE; i++){
            printf("%02x ", tag[i]);
        }
        printf("\n");
    }

    free(tag);
    return test_passed;
}

