int run_test(const char* test_name, const unsigned char key[32], const unsigned char* data, uint64_t data_len, const unsigned char true_tag[16]){
    uint32_t acc[5], r[5], s[4];
    int test_passed;
    unsigned char* tag;

    poly1305_init(acc, r, s, key); // create acc, r and s from key
    tag = create_tag(acc, r, s, data, data_len); // create the tag

    test_passed = (memcmp(tag, true_tag, 16) == 0); // test whether generated tag is equal to true tag

    if(test_passed){
        printf("%s [PASSED]\n", test_name);
    } else{
        printf("%s [FAILED]\n", test_name);
        printf("Expected tag: ");
        for(uint64_t i = 0; i < 16; i++){
            printf("%02x ", true_tag[i]);
        }
        printf("\nGenerated tag: ");
        for(uint64_t i = 0; i < 16; i++){
            printf("%02x ", tag[i]);
        }
        printf("\n");
    }

    free(tag);
    return test_passed;
}

